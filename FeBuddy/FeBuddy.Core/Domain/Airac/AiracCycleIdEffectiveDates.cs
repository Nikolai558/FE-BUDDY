/// <summary>
/// Look up AIRAC Cycle ID, and the General NASR Effective Date format along with the NASR CSV Effective Date format.
/// </summary>
/// <remarks>
/// [General] <c>yyyy-MM-dd</c> ___ [CSV] <c>dd_MMM_yyyy</c>
/// </remarks>
public class AiracCycleIdEffectiveDates
{
	/// <summary>
	/// Represents a single AIRAC cycle and its associated NASR effective date formats.
	/// </summary>
	public sealed class AiracCycleDate
	{
		/// <summary>
		/// Gets the AIRAC effective date used by NASR General data.
		/// </summary>
		/// <remarks>
		/// The date is stored in <c>yyyy-MM-dd</c> format.
		/// Example: <c>2026-09-03</c>.
		/// </remarks>
		public readonly string NasrGeneralAiracEffectiveDate;

		/// <summary>
		/// Gets the AIRAC effective date used by NASR CSV data.
		/// </summary>
		/// <remarks>
		/// The date is stored in <c>dd_MMM_yyyy</c> format using
		/// a three-letter English month abbreviation.
		/// Example: <c>03_Sep_2026</c>.
		/// </remarks>
		public readonly string NasrCsvAiracEffectiveDate;

		/// <summary>
		/// Gets the four-digit AIRAC cycle identifier.
		/// </summary>
		/// <remarks>
		/// The first two digits represent the two-digit year and the
		/// final two digits represent the AIRAC cycle number within that year.
		/// Example: <c>2609</c> represents AIRAC cycle 09 of 2026.
		/// </remarks>
		public readonly string AiracCycleId;

		/// <summary>
		/// Initializes a new instance of the <see cref="AiracCycleDate"/> class.
		/// </summary>
		/// <param name="nasrGeneralAiracEffectiveDate">
		/// The NASR General AIRAC effective date in <c>yyyy-MM-dd</c> format.
		/// Example: <c>2026-09-03</c>.
		/// </param>
		/// <param name="nasrCsvAiracEffectiveDate">
		/// The NASR CSV AIRAC effective date in <c>dd_MMM_yyyy</c> format.
		/// Example: <c>03_Sep_2026</c>.
		/// </param>
		/// <param name="airacCycleId">
		/// The four-digit AIRAC cycle identifier.
		/// Example: <c>2609</c>.
		/// </param>
		public AiracCycleDate(string nasrGeneralAiracEffectiveDate, string nasrCsvAiracEffectiveDate, string airacCycleId)
		{
			NasrGeneralAiracEffectiveDate = nasrGeneralAiracEffectiveDate;
			NasrCsvAiracEffectiveDate = nasrCsvAiracEffectiveDate;
			AiracCycleId = airacCycleId;
		}
	}

